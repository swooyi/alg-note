import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');

const [engineSource, appSource, templateText, eifTemplateText, colorsText] = await Promise.all([
  read('src/fto-engine.js'),
  read('src/app.js'),
  read('src/assets/fto-template.json'),
  read('src/assets/fto-eif-template.json'),
  read('src/assets/fto-colors.json')
]);

const engine = engineSource.replace(/^export /gm, '');
let app = appSource.replace(/^import .*?;\s*/gm, '');

const fetchBlock = `  const [template, eifTemplate, colors] = await Promise.all([
    fetch("./src/assets/fto-template.json").then((res) => res.json()),
    fetch("./src/assets/fto-eif-template.json").then((res) => res.json()),
    fetch("./src/assets/fto-colors.json").then((res) => res.json())
  ]);`;
const embeddedBlock = '  const { template, eifTemplate, colors } = EMBEDDED_ASSETS;';

if (!app.includes(fetchBlock)) {
  throw new Error('app.js의 자산 로딩 부분을 찾지 못했습니다. 정적 번들 생성 스크립트를 갱신해 주세요.');
}
app = app.replace(fetchBlock, embeddedBlock);

const assets = {
  template: JSON.parse(templateText),
  eifTemplate: JSON.parse(eifTemplateText),
  colors: JSON.parse(colorsText)
};
const solidSource = (await read('src/fto-solid.js')).replace(/^export /gm, '');
const simulatorSource = await read('src/simulator-fto.js');
const eifSource = (await read('src/fto-eif.js')).replace(/^import .*?;\s*/m, '').replace(/^export /gm, '');
const tabsSource = await read('src/fto-tabs.js');
const shareSource = await read('src/fto-share.js');
const casePlayerSource = await read('src/case-player-fto.js');
const initCall = app.match(/init\(\)\.catch\(error => \{[\s\S]*?\n\}\);/)[0];
app = app.replace(initCall, '');
const bundle = '// Generated by npm run build. Do not edit directly.\n(function () {\n' +
  'const EMBEDDED_ASSETS = ' + JSON.stringify(assets) + ';\n' +
  [engine, solidSource, eifSource, app, simulatorSource, tabsSource, shareSource, casePlayerSource,
    initCall.replace('init().catch', "init().then(() => { if (document.body.classList.contains('case-player')) initFtoCasePlayer(); }).catch")].join('\n') + '\n})();\n';
await writeFile(new URL('src/app.bundle.js', root), bundle);
console.log('Created src/app.bundle.js (integrated FTO tools)');
const casePlayerHtml = (await read('image-gen-fto.html'))
  .replace('<body class="generator-ui">', '<body class="generator-ui case-player">')
  .replace('<title>FTO Image Generator</title>', '<title>FTO case 시뮬레이터</title>')
  .replace('<link rel="stylesheet" href="./bridge.css" />', '<link rel="stylesheet" href="./src/case-player-fto.css" />')
  .replace('./src/app.bundle.js"', './src/app.bundle.js?case-player=8"')
  .replace(/\s*<script defer src="(?:\.\.\/app\/js\/[^\"]+|\.\/(?:home-bridge|bridge)\.js)"><\/script>/g, '');
await writeFile(new URL('case-player-fto.html', root), '<!-- Generated by npm run build. -->\n' + casePlayerHtml);

const cubeEngine = (await read('src/cube-engine.js')).replace(/^export /gm, '');
const cubeApp = (await read('src/cube-3x3.js')).replace(/^\uFEFF?import .*?;\s*/m, '').replace(/\ninit\(\);/, '\n');
const cubeModel = (await read('src/cube-simulator-model.js')).replace(/^import .*?;\s*/m, '').replace(/^export /gm, '');
const cubeSimulator = await read('src/simulator-3x3.js');
const cubeShare = await read('src/cube-share.js');
const cubeCasePlayer = await read('src/case-player-3x3.js');
const cubeBundle = '// Generated by npm run build. Do not edit this file directly.\n' +
  `(function () {\n'use strict';\n${cubeEngine}\n${cubeModel}\n${cubeApp}\n${cubeSimulator}\n${cubeShare}\n${cubeCasePlayer}\ninit();\ninitCubeSettingsShare();\nif (document.body.classList.contains('case-player')) initCubeCasePlayer();\n})();\n`;
await writeFile(new URL('src/cube-3x3.bundle.js', root), cubeBundle);
console.log(`Created src/cube-3x3.bundle.js (${Math.ceil(Buffer.byteLength(cubeBundle) / 1024)} KB)`);

const cubePlayerHtml = (await read('image-gen-3x3.html'))
  .replace('<body class="generator-ui">', '<body class="generator-ui case-player">')
  .replace('<title>NxNxN Image Generator</title>', '<title>3×3 case 시뮬레이터</title>')
  .replace('./bridge.css', './src/case-player-3x3.css')
  .replace('./src/cube-3x3.bundle.js"', './src/cube-3x3.bundle.js?case-player=1"')
  .replace(/\s*<script defer src="(?:\.\.\/app\/js\/[^"]+|\.\/(?:home-bridge|bridge)\.js)"><\/script>/g, '');
await writeFile(new URL('case-player-3x3.html', root), '<!-- Generated by npm run build. -->\n' + cubePlayerHtml);

const square1Engine = (await read('src/square1-engine.js')).replace(/^export /gm, '');
const square1Render = (await read('src/square1-render.js')).replace(/^import .*?;\s*/m, '').replace(/^export /gm, '');
const square1App = (await read('src/square1-app.js')).replace(/^import .*?;\s*/gm, '');
const square1Bundle = '// Generated by npm run build. Do not edit directly.\n' +
  `(function () {\n'use strict';\n${square1Engine}\n${square1Render}\n${square1App}\n})();\n`;
await writeFile(new URL('src/square1.bundle.js', root), square1Bundle);
console.log(`Created src/square1.bundle.js (${Math.ceil(Buffer.byteLength(square1Bundle) / 1024)} KB)`);
